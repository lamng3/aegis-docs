def parse(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"\s*<!--(.*?)-->\s*", text, re.S)
    meta = dict(line.split(":", 1) for line in m.group(1).strip().splitlines())
    return {k.strip(): v.strip() for k, v in meta.items()}, text[m.end() :]


def toc(body: str) -> str:
    heads = re.findall(r'<h2 id="([^"]+)">(.*?)</h2>', body)
    if len(heads) < 2:
        return ""
    items = "".join(f'<li><a href="#{i}">{t}</a></li>' for i, t in heads)
    return f'<nav class="toc"><strong>On this page</strong><ol>{items}</ol></nav>'


def main() -> None:
    for slug, label in PAGES:
        meta, body = parse((ROOT / "content" / f"{slug}.html").read_text(encoding="utf-8"))
        current = ' aria-current="page"'
        nav = "".join(f'<a href="{s}.html"{current if s == slug else ""}>{name}</a>' for s, name in PAGES)
        if slug == "index":
            (ROOT / "index.html").write_text(home_page(meta, body.strip()), encoding="utf-8")
            continue
        page = LAYOUT.format(
            title=meta.get("title", label),
            kicker=meta["kicker"],
            lede=meta["lede"],
            description=html.escape(meta["description"], quote=True),
            nav=nav,
            toc=toc(body),
            body=body.strip(),
        )
        (ROOT / f"{slug}.html").write_text(page, encoding="utf-8")
    print(f"built {len(PAGES)} pages")
    import normalize

    normalize.run(ROOT)


if __name__ == "__main__":
    main()
