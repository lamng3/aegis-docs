"""Build the Aegis manual: wrap each content/<page>.html in the shared layout.

    python3 build.py

A content file starts with a comment of `key: value` lines (title, kicker,
lede, description), then the page body. Every <h2 id="..."> becomes an entry
in the page's table of contents.
"""

from __future__ import annotations

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGES = [
    ("index", "Overview"),
    ("getting-started", "Getting started"),
    ("concepts", "Concepts"),
    ("attacks", "Attack search"),
    ("protection", "Protection"),
    ("recovery", "Recovery"),
    ("experiments", "Experiments"),
    ("reference", "Reference"),
]

LAYOUT = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} — Aegis</title>
<meta name="description" content="{description}">
<link rel="stylesheet" href="style.css">
</head>
<body>
<a class="skip" href="#content">Skip to content</a>
<header class="top">
  <a class="brand" href="index.html">Aegis</a>
  <label class="nav-button" for="nav-toggle">Menu</label>
</header>
<input id="nav-toggle" class="nav-toggle" type="checkbox">
<div class="layout">
<nav class="nav">
<a class="brand-desk" href="index.html">Aegis</a>{nav}
</nav>
<main id="content">
<p class="kicker">{kicker}</p>
<h1>{title}</h1>
<p class="lede">{lede}</p>
{toc}
{body}
</main>
</div>
<footer class="site">Aegis notes. Attack search, protection, and recovery for ontology-grounded agents. Generated by build.py.</footer>
</body>
</html>
"""


def parse(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"\s*<!--(.*?)-->\s*", text, re.S)
    meta = dict(line.split(":", 1) for line in m.group(1).strip().splitlines())
    return {k.strip(): v.strip() for k, v in meta.items()}, text[m.end() :]


def toc(body: str) -> str:
    heads = re.findall(r'<h2 id="([^"]+)">(.*?)</h2>', body)
    if len(heads) < 2:
        return ""
    items = "".join(f'<li><a href="#{i}">{t}</a></li>' for i, t in heads)
    return f'<nav class="toc"><strong>On this page</strong><ol>{items}</ol></nav>'


def main() -> None:
    for slug, label in PAGES:
        meta, body = parse((ROOT / "content" / f"{slug}.html").read_text(encoding="utf-8"))
        current = ' aria-current="page"'
        nav = "".join(f'<a href="{s}.html"{current if s == slug else ""}>{name}</a>' for s, name in PAGES)
        page = LAYOUT.format(
            title=meta.get("title", label),
            kicker=meta["kicker"],
            lede=meta["lede"],
            description=html.escape(meta["description"], quote=True),
            nav=nav,
            toc=toc(body),
            body=body.strip(),
        )
        (ROOT / f"{slug}.html").write_text(page, encoding="utf-8")
    print(f"built {len(PAGES)} pages")


if __name__ == "__main__":
    main()
